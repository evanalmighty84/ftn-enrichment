function cleanText(value = "") {
    return String(value).replace(/\s+/g, " ").trim();
}

function normalizeNeighborhoodKey(value = "") {
    return cleanText(value)
        .normalize("NFKD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/&/g, " and ")
        .replace(/[^a-z0-9]+/g, " ")
        .replace(/\s+/g, " ")
        .trim();
}

function getPolygonRecords(parsed) {
    if (Array.isArray(parsed)) {
        return parsed;
    }

    if (Array.isArray(parsed?.neighborhoods)) {
        return parsed.neighborhoods;
    }

    if (Array.isArray(parsed?.features)) {
        return parsed.features.map((feature) => ({
            ...(feature.properties || {}),
            geometry: feature.geometry || null,
        }));
    }

    return [];
}

function loadNeighborhoodPolygonIndex() {
    if (NEIGHBORHOOD_POLYGON_LOAD_ATTEMPTED) {
        return NEIGHBORHOOD_POLYGON_INDEX;
    }

    NEIGHBORHOOD_POLYGON_LOAD_ATTEMPTED = true;
    NEIGHBORHOOD_POLYGON_INDEX = new Map();

    try {
        const raw = fs.readFileSync(DFW_POLYGON_FILE, "utf8");
        const records = getPolygonRecords(JSON.parse(raw));
        let indexedKeys = 0;

        for (const rawRecord of records) {
            const record = rawRecord?.properties
                ? {
                    ...rawRecord.properties,
                    geometry: rawRecord.geometry || null,
                }
                : rawRecord;

            if (!record || typeof record !== "object") {
                continue;
            }

            const city = cleanText(record.city);
            const state = cleanText(record.state).toUpperCase();

            if (!city) {
                continue;
            }

            const candidate = {
                neighborhoodId:
                    record.neighborhood_id ?? record.id ?? null,
                name: cleanText(record.name),
                shortName: cleanText(record.short_name),
                slug: cleanText(record.slug),
                superHood: cleanText(record.super_hood),
                city,
                state,
                centroidLat: Number(record.centroid_lat),
                centroidLng: Number(record.centroid_lng),
                polygons: Array.isArray(record.polygons)
                    ? record.polygons
                    : record.geometry || null,
            };

            const keys = new Set([
                candidate.name,
                candidate.shortName,
                candidate.slug,
                candidate.superHood,
                candidate.city,
            ]);

            for (const value of keys) {
                const key = normalizeNeighborhoodKey(value);

                if (!key) {
                    continue;
                }

                if (!NEIGHBORHOOD_POLYGON_INDEX.has(key)) {
                    NEIGHBORHOOD_POLYGON_INDEX.set(key, []);
                }

                NEIGHBORHOOD_POLYGON_INDEX.get(key).push(candidate);
                indexedKeys += 1;
            }

            if (
                Number.isFinite(candidate.centroidLat) &&
                Number.isFinite(candidate.centroidLng)
            ) {
                const cityKey = normalizeNeighborhoodKey(candidate.city);

                if (cityKey && !POLYGON_CITY_COORDS.has(cityKey)) {
                    POLYGON_CITY_COORDS.set(cityKey, {
                        lat: candidate.centroidLat,
                        lon: candidate.centroidLng,
                    });
                }
            }
        }

        console.log(
            `[POLYGON] Loaded ${records.length} neighborhood record(s) ` +
            `from ${DFW_POLYGON_FILE}; indexed ${indexedKeys} key(s).`,
        );
    } catch (error) {
        console.warn(
            `[POLYGON] Could not load ${DFW_POLYGON_FILE}: ` +
            `${error.message}. Continuing with city values and ` +
            `LOCATION_OVERRIDES.`,
        );
    }

    return NEIGHBORHOOD_POLYGON_INDEX;
}

function findNeighborhoodPolygon(locationName, state) {
    const index = loadNeighborhoodPolygonIndex();
    const key = normalizeNeighborhoodKey(locationName);

    if (!index || !key) {
        return null;
    }

    const expectedState = cleanText(state).toUpperCase();
    const candidates = index.get(key) || [];
    const stateCandidates = expectedState
        ? candidates.filter(
            (candidate) =>
                !candidate.state || candidate.state === expectedState,
        )
        : candidates;

    const usable = stateCandidates.filter((candidate) => candidate.city);

    if (!usable.length) {
        return null;
    }

    const uniqueCities = new Map();

    for (const candidate of usable) {
        const cityKey = normalizeNeighborhoodKey(candidate.city);

        if (cityKey && !uniqueCities.has(cityKey)) {
            uniqueCities.set(cityKey, candidate);
        }
    }

    if (uniqueCities.size === 1) {
        return [...uniqueCities.values()][0];
    }

    // If a key is ambiguous, prefer the record whose parent city is already
    // the supplied value. Otherwise do not guess.
    const sameCity = usable.find(
        (candidate) =>
            normalizeNeighborhoodKey(candidate.city) === key,
    );

    return sameCity || null;
}

function resolveSearchLocation(city, state) {
    const originalCity = cleanText(city);
    const originalState = cleanText(state).toUpperCase();
    const polygon = findNeighborhoodPolygon(originalCity, originalState);

    if (polygon?.city) {
        return {
            city: polygon.city,
            state: polygon.state || originalState,
            source: "polygon",
            neighborhood:
                polygon.name || polygon.shortName || originalCity,
        };
    }

    const overrideCity =
        LOCATION_OVERRIDES[originalCity.toLowerCase()];

    if (overrideCity) {
        return {
            city: overrideCity,
            state: originalState,
            source: "override",
            neighborhood: originalCity,
        };
    }

    return {
        city: originalCity,
        state: originalState,
        source: "original",
        neighborhood: originalCity,
    };
}

// Title-case a name for searching: capitalize the first letter and any letter
// following a space, apostrophe, or hyphen, while preserving other capitals.
// Ensures "O'bier" / "o'bier" from the DB is searched as "O'Bier", and
// "partlow-shelton" as "Partlow-Shelton". Does NOT force-lowercase interior
// letters, so "McDonald" / "DeLuca" keep their existing capitals.
function capitalizeName(value = "") {
    const s = cleanText(value);
    if (!s) return s;
    return s.replace(
        /(^|[\s'\-])([a-z])/g,
        (_match, prefix, ch) => prefix + ch.toUpperCase(),
    );
}

// Strip trailing generational suffixes (Jr, Sr, II, III, IV, V, VI, 2nd, 3rd)
// and punctuation so "Mike Downs Jr" matches a search for "Mike Downs". This
// only loosens the comparison within the same base name - it never merges
// genuinely different names (e.g. Christa vs Kristina Roth).
const NAME_SUFFIX_RE =
    /\s+(?:jr|sr|ii|iii|iv|v|vi|vii|viii|ix|x|2nd|3rd|4th)\.?$/gi;

function normalizeNameForComparison(value = "") {
    return cleanText(value)
        .replace(NAME_SUFFIX_RE, " ")
        .replace(/[^a-z0-9\s]/gi, " ")
        .replace(/\s+/g, " ")
        .trim()
        .toLowerCase();
}

// Split a name into lowercased segments (first, middle, last, ...) after
// suffix/punctuation normalization. Hyphens become segment boundaries too.
function nameSegments(value = "") {
    return normalizeNameForComparison(value)
        .split(/[\s-]+/)
        .filter(Boolean);
}

function firstNameSegment(value = "") {
    const segs = nameSegments(value);
    return segs.length ? segs[0] : "";
}

function lastNameSegment(value = "") {
    const segs = nameSegments(value);
    return segs.length ? segs[segs.length - 1] : "";
}

function escapeRegex(value = "") {
    return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function randomDelay() {
    const min = Math.min(MIN_DELAY_MS, MAX_DELAY_MS);
    const max = Math.max(MIN_DELAY_MS, MAX_DELAY_MS);

    return min + Math.floor(Math.random() * (max - min + 1));
}

/**
 * Accept only an unmistakable two-word personal name.
 *
 * Accepted examples:
 *   Andrew Davis
 *   Willy Mac-Ossi
 *   Evan Partlow-Shelton
 *   Rachel O'Bier
 *
 * Rejected examples:
 *   Angela and Brian S.
 *   Marisol And Israel Garza
 *   Leah R.
 *   Patrick S.
 */
function parseStrictTwoWordName(author = "") {
    const clean = cleanText(author).normalize("NFC");
    const parts = clean.split(" ");

    if (parts.length !== 2) {
        return null;
    }

    const [firstName, lastName] = parts;

    const validNamePart =
        /^\p{L}[\p{L}''\-]*$/u;

    if (
        !validNamePart.test(firstName) ||
        !validNamePart.test(lastName)
    ) {
        return null;
    }

    const firstLetterCount =
        firstName.match(/\p{L}/gu)?.length || 0;

    const lastLetterCount =
        lastName.match(/\p{L}/gu)?.length || 0;

    if (firstLetterCount < 2 || lastLetterCount < 4) {
        return null;
    }

    const capFirst = capitalizeName(firstName);
    const capLastFull = capitalizeName(lastName);

    // For hyphenated last names, search using only the final segment (e.g.
    // "Partlow-Shelton" -> "Shelton") so FTN's name search/autocomplete
    // matches reliably. The full name is retained on `fullName` for result
    // matching and logging.
    const searchLastName = capLastFull.includes("-")
        ? capitalizeName(lastName.split("-").pop())
        : capLastFull;

    return {
        firstName: capFirst,
        lastName: searchLastName,
        fullName: `${capFirst} ${capLastFull}`,
    };
}

function normalizePhone(phone = "") {
    const digits = String(phone).replace(/\D/g, "");
    const tenDigits =
        digits.length === 11 && digits.startsWith("1")
            ? digits.slice(1)
            : digits;

    if (!/^[2-9]\d{9}$/.test(tenDigits)) {
        return null;
    }

    return `(${tenDigits.slice(0, 3)}) ` +
        `${tenDigits.slice(3, 6)}-` +
        `${tenDigits.slice(6)}`;
}

function parseReportedDate(text = "") {
    const match = cleanText(text).match(
        /last\s+reported\s+([A-Za-z]{3,9})\s+(\d{4})/i,
    );

    if (!match) {
        return null;
    }

    const parsed = Date.parse(`${match[1]} 1, ${match[2]}`);

    return Number.isFinite(parsed) ? parsed : null;
}

async function getRowsToEnrich() {
    // Phase 2: target only Sonar-confirmed leads (is_lead=true, set by Phase 1)
    // that Phase 2 has not yet processed. We use ftn_enriched_at (timestamptz),
    // a dedicated Phase-2-owned column, as the processed marker - NOT enriched_at
    // / enrichment_status / enrichment, which Phase 1 owns. Newest rows first
    // (id DESC) so fresh leads are prioritized. author/city/state must be present
    // for a lookup. lead_type feeds contractor routing on insert.
    const { rows } = await pool.query(
        `
            SELECT
                id,
                author,
                description,
                city,
                state,
                lead_type
            FROM ${TABLE_NAME}
            WHERE is_lead = true
              AND ftn_enriched_at IS NULL
              AND author IS NOT NULL
              AND city IS NOT NULL
              AND state IS NOT NULL
            ORDER BY id DESC
                LIMIT $1
        `,
        [MAX_ROWS],
    );

    return rows;
}

// Mark a lead as processed by Phase 2 so it is never re-picked. Writes the
// dedicated Phase-2-owned columns ftn_enriched_at / ftn_enrichment_status; the
// ftn_enriched_at IS NULL guard makes this idempotent under concurrent workers.
// Does NOT touch mobile_phone or the Phase-1-owned enriched_at /
// enrichment_status / enrichment columns.
async function markLeadProcessed(id, enrichmentStatus) {
    const { rowCount } = await pool.query(
        `
            UPDATE ${TABLE_NAME}
            SET ftn_enriched_at = now(),
                ftn_enrichment_status = $1
            WHERE id = $2
              AND ftn_enriched_at IS NULL
        `,
        [enrichmentStatus, id],
    );

    return rowCount > 0;
}

// Normalize a Postgres text[] (or stray scalar) into lowercased, trimmed,
// non-empty strings for case-insensitive comparison. Never splits an element
// on commas - malformed comma-joined entries are compared as-is.
function normalizeStringArray(value) {
    const arr = Array.isArray(value)
        ? value
        : value == null || value === ""
            ? []
            : [value];

    return arr
        .map((item) => cleanText(item).toLowerCase())
        .filter(Boolean);
}

// familytreenow.lead_type is a single text column. Join a text[] lead_type with
// commas (dropping empties); return null for empty/absent so the column is NULL.
function formatLeadTypeForFamilyTreeNow(leadType) {
    if (Array.isArray(leadType)) {
        const parts = leadType
            .map((item) => cleanText(item))
            .filter(Boolean);

        return parts.length ? parts.join(",") : null;
    }

    const single = cleanText(leadType);
    return single || null;
}

// All verified contractors, fetched once per worker process and cached so we
// don't re-query users for every lead in the batch.
let VERIFIED_CONTRACTORS = null;

async function getVerifiedContractors() {
    if (VERIFIED_CONTRACTORS) {
        return VERIFIED_CONTRACTORS;
    }

    const { rows } = await pool.query(
        `
            SELECT
                id,
                name,
                company_name,
                phone_number,
                industry,
                subscribed_areas,
                state
            FROM users
            WHERE verified = true
        `,
    );

    VERIFIED_CONTRACTORS = rows;
    return rows;
}

// Given a lead's lead_type[] and resolved city/state, find verified contractors
// to route this lead to. Returns parallel arrays for familytreenow's
// company_name[] and professionalnumbertocall[]. Matching is case-insensitive:
//   0. STATE: contractor.state must equal the lead state (when both present) -
//      "Arlington" exists in TX and VA, so an out-of-state contractor must not
//      route a TX lead.
//   1. INDUSTRY: contractor.industry[] must intersect lead.lead_type[], after
//      normalizing both sides (spaces AND hyphens -> underscores) so users data
//      like "general contractor" matches canonical "general_contractor".
//   2. PHONE: only contractors with a non-empty phone_number are routable - a
//      phoneless contractor is excluded entirely and never suppresses nearby.
//   3. CITY (exact): expanded subscribed_areas contains the resolved city.
//   4. CITY (nearby): only if exact matched nobody - an expanded subscribed_areas
//      city is within NEARBY_CONTRACTOR_MILES of the resolved city (seed-geocoded).
async function routeContractors(leadType, resolvedCity, state) {
    const empty = { companyNames: [], phones: [] };

    // Industry tokens: lowercase + trim (via normalizeStringArray) then map
    // spaces AND hyphens to underscores so canonical/legacy spellings unify.
    const toIndustryTokens = (value) =>
        normalizeStringArray(value).map((item) =>
            item.replace(/[\s-]+/g, "_"),
        );

    const leadTypes = toIndustryTokens(leadType);

    if (!leadTypes.length) {
        return empty;
    }

    const leadTypeSet = new Set(leadTypes);
    const leadState = cleanText(state).toUpperCase();
    const contractors = await getVerifiedContractors();

    // (0) State filter - require equality when both states are present. A
    // missing contractor state does not disqualify (can't prove a mismatch).
    const stateMatched = contractors.filter((contractor) => {
        const contractorState = cleanText(contractor.state).toUpperCase();

        if (!leadState || !contractorState) {
            return true;
        }

        return contractorState === leadState;
    });

    // (1) Industry filter.
    const industryMatched = stateMatched.filter((contractor) =>
        toIndustryTokens(contractor.industry).some((industry) =>
            leadTypeSet.has(industry),
        ),
    );

    // (2) Usable-phone filter, applied BEFORE city matching so phoneless
    // contractors neither route nor suppress the nearby fallback.
    const routable = industryMatched.filter((contractor) => {
        const phone =
            contractor.phone_number == null
                ? ""
                : String(contractor.phone_number).trim();

        return phone.length > 0;
    });

    if (!routable.length) {
        return empty;
    }

    // Expand each contractor's subscribed_areas: split every element on ",",
    // trim each piece, drop empties, lowercase. Handles the malformed
    // single comma-joined string (e.g. "Allen,Plano,Garland,...").
    const expandedAreas = (contractor) => {
        const raw = Array.isArray(contractor.subscribed_areas)
            ? contractor.subscribed_areas
            : contractor.subscribed_areas == null ||
            contractor.subscribed_areas === ""
                ? []
                : [contractor.subscribed_areas];

        const out = [];

        for (const element of raw) {
            for (const piece of String(element).split(",")) {
                const cityPiece = cleanText(piece).toLowerCase();
                if (cityPiece) {
                    out.push(cityPiece);
                }
            }
        }

        return out;
    };

    const cityKey = cleanText(resolvedCity).toLowerCase();

    // (3) Exact city tier.
    let matched = routable.filter((contractor) =>
        expandedAreas(contractor).includes(cityKey),
    );

    if (!matched.length) {
        // (4) Nearby tier. A subscribed city missing from the coordinate seed
        // geocodes to null and cannot participate - only exact match applies.
        const target = await geocodeCity(resolvedCity, state);

        if (target) {
            const nearby = [];

            for (const contractor of routable) {
                let isNear = false;

                for (const area of expandedAreas(contractor)) {
                    const coord = await geocodeCity(area, state);

                    if (
                        coord &&
                        haversineMiles(target, coord) <=
                        NEARBY_CONTRACTOR_MILES
                    ) {
                        isNear = true;
                        break;
                    }
                }

                if (isNear) {
                    nearby.push(contractor);
                }
            }

            matched = nearby;
        }
    }

    const companyNames = [];
    const phones = [];
    const seenPhones = new Set();

    for (const contractor of matched) {
        const phone = String(contractor.phone_number).trim();

        // Dedupe by phone_number (case-insensitive), preserving order. Every
        // contractor in `matched` already has a non-empty phone (routable).
        const key = phone.toLowerCase();
        if (seenPhones.has(key)) {
            continue;
        }
        seenPhones.add(key);

        companyNames.push(contractor.company_name ?? null);
        phones.push(contractor.phone_number);
    }

    return { companyNames, phones };
}

